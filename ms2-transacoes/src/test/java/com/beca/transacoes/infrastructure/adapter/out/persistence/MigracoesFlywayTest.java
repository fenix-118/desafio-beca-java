package com.beca.transacoes.infrastructure.adapter.out.persistence;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * As migrações de verdade, num H2 em memória, sem Spring: banco novo e banco antigo (de antes do câmbio,
 * criado pelo ddl-auto: update) terminam com o mesmo esquema.
 */
class MigracoesFlywayTest {

    private static final String COLUNAS_DO_CAMBIO = "select count(*) from information_schema.columns "
            + "where lower(table_name) = 'transacoes' and lower(column_name) in "
            + "('cotacao_usd', 'data_cotacao_usd', 'cotacao_eur', 'data_cotacao_eur')";

    private static Flyway flyway(String url) {
        return Flyway.configure()
                .dataSource(url, "sa", "")
                .locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion("1")
                .load();
    }

    private static int contar(String url, String sql) throws SQLException {
        try (Connection c = DriverManager.getConnection(url, "sa", "");
             Statement s = c.createStatement();
             ResultSet r = s.executeQuery(sql)) {
            r.next();
            return r.getInt(1);
        }
    }

    @Test
    void bancoNovoRodaAV1EAV2() throws SQLException {
        String url = "jdbc:h2:mem:banco-novo;DB_CLOSE_DELAY=-1";

        Flyway migracoes = flyway(url);
        migracoes.migrate();

        assertThat(migracoes.info().current().getVersion().getVersion()).isEqualTo("2");
        assertThat(contar(url, COLUNAS_DO_CAMBIO)).isEqualTo(4);
    }

    @Test
    void bancoAntigoSemAsColunasDoCambioRecebeBaselineEAV2CompletaAsColunas() throws SQLException {
        String url = "jdbc:h2:mem:banco-antigo;DB_CLOSE_DELAY=-1";
        try (Connection c = DriverManager.getConnection(url, "sa", "");
             Statement s = c.createStatement()) {
            // A tabela como o ddl-auto: update criava antes do pedido 3 (sem as colunas da cotação).
            s.execute("""
                    CREATE TABLE transacoes (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        usuario_id BIGINT NOT NULL, tipo VARCHAR(20) NOT NULL, valor NUMERIC(15, 2) NOT NULL,
                        categoria VARCHAR(20), usuario_destino_id BIGINT, descricao VARCHAR(140),
                        status VARCHAR(20) NOT NULL, motivo_rejeicao VARCHAR(40),
                        criada_em TIMESTAMP(6) WITH TIME ZONE NOT NULL)
                    """);
            s.execute("INSERT INTO transacoes (usuario_id, tipo, valor, status, criada_em) "
                    + "VALUES (1, 'DEPOSITO', 100.00, 'APROVADA', CURRENT_TIMESTAMP)");
        }

        Flyway migracoes = flyway(url);
        migracoes.migrate();

        // O baseline marca a V1 como aplicada sem rodar; a V2 roda e cria as colunas que faltavam.
        assertThat(migracoes.info().current().getVersion().getVersion()).isEqualTo("2");
        assertThat(contar(url, COLUNAS_DO_CAMBIO)).isEqualTo(4);
        assertThat(contar(url, "select count(*) from transacoes")).isEqualTo(1);
    }
}
