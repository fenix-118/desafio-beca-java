-- Esquema inicial do MS2, igual ao que o Hibernate criava com ddl-auto: update (conferido com pg_dump em 11/11/2026).
-- Bancos que já tinham a tabela recebem só o baseline (spring.flyway.baseline-on-migrate) e não rodam este script.
CREATE TABLE transacoes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    usuario_id         BIGINT                      NOT NULL,
    tipo               VARCHAR(20)                 NOT NULL,
    valor              NUMERIC(15, 2)              NOT NULL,
    categoria          VARCHAR(20),
    usuario_destino_id BIGINT,
    descricao          VARCHAR(140),
    status             VARCHAR(20)                 NOT NULL,
    motivo_rejeicao    VARCHAR(40),
    criada_em          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    cotacao_usd        NUMERIC(12, 6),
    data_cotacao_usd   DATE,
    cotacao_eur        NUMERIC(12, 6),
    data_cotacao_eur   DATE,
    CONSTRAINT transacoes_pkey PRIMARY KEY (id),
    CONSTRAINT transacoes_tipo_check
        CHECK (tipo IN ('DEPOSITO', 'RETIRADA', 'TRANSFERENCIA', 'COMPRA')),
    CONSTRAINT transacoes_categoria_check
        CHECK (categoria IN ('ALIMENTACAO', 'TRANSPORTE', 'MORADIA', 'LAZER', 'SAUDE', 'EDUCACAO', 'OUTROS')),
    CONSTRAINT transacoes_status_check
        CHECK (status IN ('PENDENTE', 'APROVADA', 'REJEITADA'))
);

CREATE INDEX idx_transacoes_usuario_data ON transacoes (usuario_id, criada_em);
